# Builds shaders/lang/*.lang from the readable UTF-8 sources in lang_src/*.txt.
# Screen order and contents come from shaders.properties, option names are colored by performance cost,
# and all non-ASCII is escaped as \uXXXX (Iris breaks on non-ASCII in .properties-like files).
# Usage: python3 lang_src/gen.py
import re, os
ROOT = os.path.dirname(os.path.abspath(__file__))
SH = os.path.join(ROOT, '..', 'shaders')
props = open(os.path.join(SH, 'shaders.properties')).read()
screens = re.search(r'^screen=(.*)$', props, re.M).group(1).replace('[', '').replace(']', '').split()

# performance cost: everything not listed here is green
YELLOW = {'HELD_LIGHT', 'PORTAL_LIGHT', 'ORE_LIGHT_RADIUS', 'ORE_LIGHT_DIST', 'NETHER_HAZE', 'GLOW', 'FXAA', 'SHARPEN'}
RED = {'ORE_LIGHT'}
CODES = {'G': '§a', 'Y': '§e', 'C': '§c', 'R': '§r'}

def load(lang):
    d = {}
    for l in open(os.path.join(ROOT, lang + '.txt'), encoding='utf-8'):
        l = l.rstrip('\n')
        if '=' in l:
            k, v = l.split('=', 1)
            d[k] = v
    return d

def esc(s):
    return ''.join(c if ord(c) < 128 else '\\u%04x' % ord(c) for c in s)

en = load('en_us')
for lang in sorted(f[:-4] for f in os.listdir(ROOT) if f.endswith('.txt')):
    d = load(lang)
    miss, extra = set(en) - set(d), set(d) - set(en)
    assert not miss and not extra, (lang, miss, extra)
    legend = d['LEGEND']
    for k, v in CODES.items():
        legend = legend.replace('{' + k + '}', v)
    out = ['# generated by lang_src/gen.py, edit lang_src/*.txt instead', '']
    used = {'LEGEND'}
    for sid in screens:
        out += [f'screen.{sid}={d["screen." + sid]}', f'screen.{sid}.comment={legend}']
        used.add('screen.' + sid)
        for o in re.search(rf'^screen\.{sid}=(.*)$', props, re.M).group(1).split():
            if o == '<empty>':
                continue
            col = CODES['C'] if o in RED else CODES['Y'] if o in YELLOW else CODES['G']
            out.append(f'option.{o}={col}{d[o]}')
            used.add(o)
            if o + '.comment' in d:
                out.append(f'option.{o}.comment={d[o + ".comment"]}')
                used.add(o + '.comment')
            for k in d:
                if k.startswith(f'value.{o}.'):
                    out.append(f'{k}={d[k]}')
                    used.add(k)
        out.append('')
    assert used == set(d), (lang, set(d) - used)
    open(os.path.join(SH, 'lang', lang + '.lang'), 'w').write(esc('\n'.join(out)))
    print(lang)
